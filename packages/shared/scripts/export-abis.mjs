// Regenerates src/abis/generated.ts from Foundry build artifacts (contracts/out).
// Run `forge build` in /contracts first: `pnpm contracts:build && pnpm contracts:abi`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const contracts = [
  ["AtlasLaunchpad", "atlasLaunchpadAbi"],
  ["AtlasGovernor", "atlasGovernorAbi"],
  ["NationTreasury", "nationTreasuryAbi"],
  ["NationToken", "nationTokenAbi"],
];

let src = "// AUTO-GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [name, exportName] of contracts) {
  const artifact = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8"));
  src += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(here, "../src/abis/generated.ts"), src);
console.log(`Wrote ${contracts.length} ABIs to src/abis/generated.ts`);
